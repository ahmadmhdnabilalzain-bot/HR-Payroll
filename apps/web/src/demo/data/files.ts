import {
  askSeeds,
  checkDays,
  clockSites,
  CORRECTION_STATUS,
  COVER_NOTE,
  coverLeave,
  dailyRate,
  DOC_TYPES,
  ENCASH_NOTE,
  encashable,
  encashQuote,
  EXIT_QUESTIONS,
  EXIT_REASONS,
  EXIT_SCALE,
  exitCandidates,
  exitInterviews,
  FILES_NOTE,
  GEOFENCE_NOTE,
  leaveHalves,
  leaveLiability,
  leaveSafeCheck,
  LIABILITY_NOTE,
  onFile,
  phonePunches,
  RECORD_NOTE,
  SIGNATURE_NOTE,
  signDocs,
  wfhRows,
  WFH_NOTE,
  AS_OF,
  type DemoCompany,
} from "@payroll/demo-data";
import type { FilesData } from "./files-types";

/** The WP17 view over the demo company. Imported only by adapter.ts. */
export function adaptFiles(c: DemoCompany): FilesData {
  return {
    asOf: AS_OF,
    exit: { interviews: () => exitInterviews(c),
      candidates: () => exitCandidates(c), reasons: EXIT_REASONS,
      questions: EXIT_QUESTIONS, scale: EXIT_SCALE },
    sign: { docs: () => signDocs(c), note: SIGNATURE_NOTE },
    files: { onFile: () => onFile(c), types: DOC_TYPES, note: FILES_NOTE },
    leave: { encashable: () => encashable(c),
      quote: (id, halves) => encashQuote(c, id, halves),
      seeds: () => askSeeds(c), liability: () => leaveLiability(c),
      rate: (id) => dailyRate(c, id), halves: leaveHalves,
      encashNote: ENCASH_NOTE, liabilityNote: LIABILITY_NOTE,
      recordNote: RECORD_NOTE },
    clock: { checkDays: () => checkDays(c), statuses: CORRECTION_STATUS,
      sites: () => clockSites(c), phone: () => phonePunches(c),
      geofenceNote: GEOFENCE_NOTE, wfh: () => wfhRows(c),
      wfhNote: WFH_NOTE },
    cover: { leave: () => coverLeave(c),
      check: (extra) => leaveSafeCheck(c, extra), note: COVER_NOTE },
  };
}
